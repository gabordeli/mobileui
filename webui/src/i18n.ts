const KEY = "mobileui.locale";

function initialLocale(): Locale {
  const stored = localStorage.getItem(KEY);
  if (stored === "hu" || stored === "en") return stored;
  return navigator.language.toLowerCase().startsWith("hu") ? "hu" : "en";
}

